#!/usr/bin/env node
/**
 * Embed MCP bridge source only. Skills/rules come from SkillProvider /
 * RulesProvider at runtime (not baked into the plugin).
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const packRoot = join(here, '../packs/graph-kg');
const outDir = join(here, '../src/tools/runtime');
const outFile = join(outDir, 'ephemeral-pack.generated.ts');

function lit(s) {
  return JSON.stringify(s);
}

const bridge = readFileSync(join(packRoot, 'bin/instance-mcp.mjs'), 'utf8');

mkdirSync(outDir, { recursive: true });
writeFileSync(
  outFile,
  [
    '/* Generated by scripts/embed-ephemeral-pack.mjs — do not edit. */',
    `export const INSTANCE_MCP_SOURCE = ${lit(bridge)};`,
    '',
  ].join('\n'),
);
console.log('wrote', outFile);
